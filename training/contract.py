# 비트가 그 3건의 계산 경로에 없다.
#
#   가중치의 신원  → **model_sha 가 전담한다** (돌연변이 생존율 0/20)
#   이 카나리아    → **라벨 순서 · 토크나이저 · 출력 차원 · 그래프 결합성**
#
# 그래서 이름이 "파이프라인 카나리아"다. 두 장치가 서로 다른 실패를 맡으므로 어느 쪽도
# 다른 쪽을 대신하지 않는다 — 입력을 3건에서 50건으로 늘려 가중치까지 덮게 만들 수도
# 있지만, 그건 sha 가 이미 100% 하고 있는 일을 기동 시간을 내고 다시 하는 것이다.
#
# 무엇을 못 잡는가: **옛 프로세스가 옛 모델을 서빙하는 경우** — 그쪽은 자기 카나리아를
# 통과한다(자기 모델로 구운 정답이므로). 그 자리는 model_stale이 맡는다.
