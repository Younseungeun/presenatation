#
# **파일마다 지문을 하나씩 더 다는 것은 블랙리스트 방어라 끝이 없다.**
# 세 회차 연속으로 같은 모양의 결함이 나왔고(학습셋=채점지 / 죽은 그래프 / 옛 가중치),
# 공통점은 "이름은 맞는데 내용이 다르다"였다. 개별 이름을 하나씩 대조하는 대신,
# **파이프라인이 통째로 같은 답을 내는지**를 한 자리에서 본다.
#
# ⚠ **가중치 무결성 검사가 아니다** (11차 K-3 — 실측으로 이름을 고쳤다).
#
# 원래 주석은 "가중치·라벨 순서·토크나이저·차원 중 하나라도 어긋나면 잡는다"였는데,
# 돌연변이 시험(training/mutation_test.py)이 그 첫 항목을 반증했다: 파일 이름을 그대로
