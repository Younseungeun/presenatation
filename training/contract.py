def tokenizer_fingerprint(base: str) -> str:
    """토크나이저 파일들의 내용 해시. **학습과 서빙이 같은 값을 내야 한다.**

    다르면 예외가 아니라 **조용히 틀린 답**이 나온다 — 임베딩 벡터에 모델 식별자를
    함께 저장하는 것과 같은 종류의 방어다. 그래서 값을 믿지 않고 지문을 대조한다.

    파일 이름이 아니라 **내용**을 해싱한다: 같은 경로에 다른 파일이 놓여도 이름은 그대로다.
    정렬해 이어 붙인다: 디렉터리 순회 순서는 OS마다 다르다.
    """
    root = Path(base)
    if not root.is_dir():
        return f"nonlocal:{base}"  # 허브 이름으로 돌린 경우 — 지문을 만들 수 없다
    h = hashlib.sha256()
    for name in sorted(p.name for p in root.iterdir() if p.is_file()):
        # 이 모델에는 special_tokens_map.json이 없다(실제 확인). 있으면 함께 센다
        if "token" in name or name in ("vocab.txt", "special_tokens_map.json"):
            h.update(name.encode())
            h.update((root / name).read_bytes())
    return h.hexdigest()[:16]

