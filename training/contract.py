# **기대값을 손으로 적지 않는다.** 로짓 문턱을 코드에 박으면 재학습할 때마다 카나리아가
# 깨지고, 그렇다고 매번 다시 구우면 아무것도 주장하지 않는 기록이 된다. 대신
