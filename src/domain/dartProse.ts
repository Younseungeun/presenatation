/**
 * @근거 시뮬 — scripts/probeDartProseRefine.ts (25차).
 *   ① 서술형 종결(다/요/까/오): 표 조각·표제어·개조식(…함/…임)은 술어로 끝나지 않는다
 *   ② 조사 1회 이상: 명사 나열(표 행)에는 조사가 없다
 *   ③ 4어절 이상: 파편 제거 (5어절은 채점지 위반 "이 전략은 원금을 보장합니다."를 찢었다)
 */
export function isRefinedProse(s: string): boolean {
  const t = s.trim();
  if (!/(다|요|까|오)[.!?]?$/.test(t)) return false;
  if (!/[가-힣][은는이가을를에의로와과]\s/.test(t)) return false;
  if (t.split(/\s+/).filter(Boolean).length < 4) return false;
  return true;
}

