// 신고 누적에 의한 가역적 판매 중단 — **한 사람의 말로는 아무것도 멈추지 않는다.**
//
// 신고 1건에 판매를 멈추면 무기가 된다: 신고는 공짜이고(하루 3건), 판매 기간은
// `min(검증기간/3, 30일)`이라 **한 번 지나간 날은 안 돌아온다.** 게다가 신고에는 보상이
// 걸려 있어, 즉시 중단을 붙이면 같은 버튼이 무기와 급여를 동시에 쥐여준다.
//
// 되돌리는 비용이 양쪽으로 다른 것이 이 설계의 전부다:
//   · 잘못 중단 → **복구 불가**. 잃은 판매 기간을 메우는 장치가 없다
//     (플랫폼 귀책 보상은 판정 불가를 덮지 잃은 판매를 덮지 않는다)
//   · 안 막았는데 위반이 확인됨 → **복구 가능**. 강제 철회가 이미 있다
//     (전액 환불 · 수수료 0 · 점수 0)
// 한쪽에만 복구 장치가 있으면 확신이 없을 때 그쪽으로 기울이는 것이 맞다.
//
// 그래서 멈추는 근거를 **신고자 수**에 둔다. 1인 1계정(본인 인증 CI 해시)이 이미 있어
// 서로 다른 신고자 N명은 실명 인증된 사람 N명이고, 위조하려면 번호 N개 + 본인 인증 N회가
// 든다 — **어뷰징 방어가 이미 비싸게 만들어 둔 것을 그대로 빌린다.**

/**
 * 판매를 멈추는 서로 다른 신고자 수.
 *
 * @근거 설계 — 위조 비용을 이미 있는 1인 1계정(본인 인증 CI 해시)에서 빌린다. 2명은
 * 공범 하나면 성립해 낮고, 3명은 실명 인증된 사람 셋이 같은 리포트를 가리켜야 한다.
 * 결정적으로 **2·3번째 신고자는 보상을 못 받는다**(리포트별 첫 신고자만 대상이고 화면이
 * 그 사실을 먼저 알린다) — 즉 판매를 멈추는 힘은 **보상 없이 움직인 사람들**에게서만
 * 나온다. 돈과 권한이 분리되어, 보상 사냥꾼이 노리는 첫 자리로는 아무것도 멈추지 않는다.
 */
export const ABUSE_SUSPEND_REPORTERS = 3;

/**
 * 중단은 **아직 안 본 신고(PENDING)만** 센다.
 *
 * 이 장치가 대신하는 것은 **운영자의 부재**다 — "아직 아무도 안 봤는데 이만큼이 여기를
 * 가리키니 보는 동안은 팔지 말자". 운영자가 보고 난 뒤의 판단은 운영자의 도구
 * (강제 철회)가 할 일이지 카운터가 할 일이 아니다. 그래서 **사람이 도착하는 순간
 * 이 카운터는 의미를 잃는다.**
 *
 * 확인(CONFIRMED)까지 세면 다른 결함이 생긴다: 위반은 맞지만 철회할 정도는 아니라고
 * 판단한 리포트가 **영원히 중단된 채 갇힌다**(확인을 되돌리는 상태 전이가 없다).
 * 대신 "확인했는데 아직 판매 중"인 경우를 운영자에게 따로 일러 준다
 * (abuseReportService.reviewAbuseReport의 철회 환기 알림).
 */
export function suspendsOnAbuseReports(distinctPendingReporters: number): boolean {
  return distinctPendingReporters >= ABUSE_SUSPEND_REPORTERS;
}

/**
 * 구매자에게 보이는 문구 — **사유를 쓰지 않는다.**
 *
 * "신고 누적"이라고 적으면 확인되지 않은 혐의를 시장에 방송하는 것이 된다.
 * 판매 마감 사유를 공개하지 않는 규칙과 같은 자리다(salesWindow: 사유가 공개되면
 * 조합으로 종목이 좁혀진다). 여기서는 이유가 하나 더 있다 — 검토 결과 기각되면
 * 이 리포트는 다시 팔리는데, 그때 남는 것은 방송된 혐의뿐이기 때문이다.
 */
export const ABUSE_SUSPENDED_MESSAGE =
  '이 리포트는 확인 중이라 판매가 일시 중단되었습니다. 확인이 끝나면 다시 구매할 수 있습니다.';
