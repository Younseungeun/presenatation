// **시험은 학생 검사기를 명시적으로 끄고 시작한다** (Q0 정책 전환 후 필수).
//
// ── 왜 이 파일이 생겼나 (2026-08-21 실측) ────────────────────────────
// 개발용 .env 에 STUDENT_SIDECAR_URL 이 있어서 시험 프로세스가 그대로 물려받으면
// 모드가 live 로 계산된다. 사이드카는 시험 중 안 떠 있으므로 — 새 정책(검사기가 죽으면
// 게시 보류)이 정확히 설계대로 **모든 게시를 보류**시켰고, 게시를 전제로 하는
// DB 시험 130건이 한꺼번에 빨개졌다.
//
// 예전에는 이 상태가 조용히 통과했다 — "학생이 죽어도 그냥 게시"라는 옛 정책 덕분에
// 시험이 **장애 상태에서 돌고 있다는 사실 자체가 안 보였다.** 빨간불이 맞는 신호였고,
// 처방은 정책을 되돌리는 것이 아니라 시험 환경을 정직하게 만드는 것이다:
// 시험은 "학생 없음(off)"이라는 **의도된 끔**으로 돈다.
//
// 학생의 라이브·장애 동작을 재는 시험(studentLive·studentOutage)은 env 를 직접 주거나
// ctx 를 직접 넘기므로 이 기본값의 영향을 받지 않는다.
process.env.STUDENT_MODE = 'off';
delete process.env.STUDENT_SIDECAR_URL;
