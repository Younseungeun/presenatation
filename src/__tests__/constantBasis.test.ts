import { describe, expect, it } from 'vitest';
import { auditConstants, BASIS_KINDS, DEBT_FILE } from '../../scripts/lib/constantAudit';

// **숫자 상수는 근거와 함께 산다** — 값이 아니라 값의 이유가 코드에 남아야 한다.
//
// ── 왜 이것이 시험할 만한 성질인가 ──────────────────────────
// 이 저장소는 이미 주석을 아주 길게 쓴다. 문제는 문서가 없는 것이 아니라
// **문서가 있는지 아무도 확인하지 않는다**는 것이었다. 실제로 걸린 사고가 있다:
// `EQUITY_SHORT_HORIZON_DAYS = 7`은 주석이 한 줄도 없었고, 왜 7인지 아무도 몰랐고,
// 38차에서 시뮬레이션을 새로 돌려 보니 **14가 맞았다.** 1,020개 테스트 중 그 값을
// 붙잡는 것이 하나도 없어 7→14가 조용히 통과했다 — 즉 그 값은 아무것도 지키고
// 있지 않았다. 근거 없는 값은 틀렸다는 사실조차 알려 주지 않는다.
//
// ── 래칫의 모양 (41차 검토 ②안: 베이스라인) ─────────────────
// 현재 개수를 못 박으면 "45개나 46개나" 하는 깨진 유리창이 된다. 그래서 **개수가
// 아니라 이름**을 박는다. 규칙은 둘뿐이다:
//
//   근거가 없다  → `constants-debt.txt`에 그 이름이 있어야 한다
//   근거가 생겼다 → 그 이름을 목록에서 지워야 한다
//
// 새 상수는 목록에 없으므로 **근거를 적지 않으면 반드시 실패한다.** 빚을 늘리는 유일한
// 길은 목록에 손으로 한 줄을 더하는 것이고, 그 파일은 빚 말고 아무것도 담고 있지
// 않으므로 그 한 줄이 리뷰에서 그대로 보인다. **코드가 막을 수 있는 데까지 막고,
// 나머지는 보이게 만든다** — 이 시험이 하는 일의 정확한 범위다.
//
// ── 왜 `@근거 미기록` 태그를 두지 않았나 ────────────────────
// 검토안은 `미기록`을 어휘에 넣자고 했다. 태그는 복사된다 — 새 상수를 쓰는 사람은
// 옆 상수를 복사하고, 옆에 `미기록`이 붙어 있으면 그것까지 따라온다. 그러면 빚이
// 코드 안에서 스스로 번식한다. 태그가 아예 없으면 복사할 것도 없다.

const ROOT = process.cwd();

describe('숫자 상수에는 근거가 붙어 있다', () => {
  const result = auditConstants(ROOT);

  it('근거가 없는 상수는 전부 면제 목록에 이름이 있다', () => {
    const names = result.untracked.map((s) => `${s.file}:${s.line}  ${s.name}`);
    expect(
      names,
      `새 숫자 상수에는 근거를 적으세요:\n` +
        `    /** @근거 ${BASIS_KINDS.join('|')} <왜 이 값인지 한 줄> */\n` +
        `  시뮬=측정해서 나온 값(스크립트 경로를 적는다) · 규칙=거래소·법·계약이 정한 값\n` +
        `  계약=상대와 합의한 값 · 설계=우리가 고른 값(고른 이유를 적는다)\n` +
        `  근거를 지금 댈 수 없다면 ${DEBT_FILE}에 이름을 올리세요 — 그 줄이 빚입니다.`,
    ).toEqual([]);
  });

  it('근거 태그의 형식이 지켜진다', () => {
    const bad = result.malformed.map((m) => `${m.site.file}:${m.site.line}  ${m.site.name} — ${m.why}`);
    expect(bad, '태그가 도장이 되지 않게 종류와 이유를 모두 검사합니다.').toEqual([]);
  });

  it('근거를 적은 상수는 면제 목록에서 지워져 있다', () => {
    expect(
      result.paid.map((s) => s.key),
      `근거가 생겼으니 ${DEBT_FILE}에서 이 줄들을 지우세요.\n` +
        `  지우지 않으면 목록의 줄 수가 남은 빚의 양이라는 성질이 깨집니다.`,
    ).toEqual([]);
  });

  it('면제 목록에 유령 이름이 없다', () => {
    expect(
      result.stale,
      `${DEBT_FILE}에 있는데 그런 상수가 없습니다 — 이름이 바뀌었거나 지워졌습니다.\n` +
        `  유령을 남겨 두면 목록이 빚의 양을 부풀려 세게 됩니다.`,
    ).toEqual([]);
  });

  it('스캐너가 실제로 무언가를 보고 있다', () => {
    // 스캐너가 조용히 0개를 훑고 통과하는 것이 이 시험의 가장 위험한 실패다
    // (경로가 바뀌거나 파서가 깨지면 모든 검사가 빈 배열로 성공한다)
    expect(result.sites.length).toBeGreaterThan(100);
    expect(result.sites.filter((s) => s.basis).length).toBeGreaterThan(50);
  });
});
