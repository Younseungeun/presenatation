// 카드 배경 궤적이 무엇인지 밝히는 한 줄.
//
// 배경에 차트 모양이 깔려 있으면 "이 리포트 종목의 실제 차트"로 읽힐 여지가 있다.
// 구매 전에는 종목 자체를 마스킹하므로 그럴 수가 없지만, 소비자가 거기까지 추론하지는
// 않는다. 그래서 **무엇이 아닌지**보다 **무엇인지**를 먼저 말한다 — 정체를 알면
// 오해는 따라서 사라지고, 부정문만 쓰면 오히려 차트로 인식시킨 뒤 부정하는 꼴이 된다.
//
// 카드마다 붙이지 않고 궤적이 등장하는 화면마다 한 번만 둔다.
// 카드 38장에 각각 달면 노이즈일 뿐 아니라, 그 반복이 배경을 더 차트처럼 보이게 만든다.
export function TraceNotice({ className }: { className?: string }) {
  return (
    <p
      className={className}
      style={{
        fontSize: 11.5,
        lineHeight: 1.6,
        color: "var(--text-faint)",
        margin: "10px 0 14px",
      }}
    >
      카드 배경의 그래프는 예측의 방향·크기·기간을 요약한 그림입니다. 실제 종목의 시세
      차트가 아니에요.
    </p>
  );
}
