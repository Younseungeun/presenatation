import { notFound } from "next/navigation";
import { RecoveryForm } from "./RecoveryForm";

// 비상 복구 화면 (2026-08-17 검토 7차 Q1) — **로그인 밖에 있고, 기본은 꺼져 있다.**
//
// /admin 아래에 두면 안 된다. 그쪽은 운영자 세션과 패스키 관문이 지키는 구역인데,
// 이 화면이 필요한 상황은 정확히 **그 둘 다 불가능한 상황**이다.
//
// ── 왜 기본이 꺼짐인가 (2026-08-17 사용자 확정) ────────────────
// 이 경로가 필요한 상황은 **본인 인증 불가 + 쓸 수 있는 기기 0개**가 겹칠 때뿐이고,
// 예비 기기(공기계 패스키)가 오른쪽을 이미 막는다. 게다가 창업자는 서버를 쥐고 있어
// 앱에서 잠겨도 서버 쪽으로 들어갈 수 있다 — 즉 이것은 **유일한 복구 수단이 아니라,
// 급할 때 코드를 고쳐 배포하지 않아도 되는 수단**이다.
//
// 그래서 출시 요건에서 뺐다. 다만 코드는 지우지 않는다 — `RECOVERY_PUBLIC_KEY`를
// 넣지 않으면 **이 화면도 API도 존재하지 않고**(404), 유지 비용이 0이다.
// 나중에 필요해지면 종이를 만들어 환경 변수에 넣기만 하면 그때 켜진다.
//
// 화면과 API가 **같은 조건으로** 닫혀야 한다. API만 닫으면 화면은 떠서 표를 붙여
// 넣게 해 놓고 마지막에 404를 뱉는데, 그 순간 사용자는 자기 표가 잘못된 줄 안다 —
// 하필 그 표가 금고를 열어 만든 1회용이다.
//
// ⚠ 디자인 보류 — 기능만 있는 최소 화면이다(docs/design-backlog.md).

export const metadata = { title: "비상 복구" };

export default function RecoveryPage() {
  if (!process.env.RECOVERY_PUBLIC_KEY?.trim()) notFound();
  return <RecoveryForm />;
}
