/**
 * **앱에서 이 사람을 부르는 이름 하나** (2026-08-20 사용자 지시).
 *
 * MY 화면이 이용자 본인에게 보여 주는 이름과 관리 화면이 그 사람을 가리키는 이름은
 * **같아야 한다.** 다르면 운영자가 쪽지에 쓴 이름을 받는 사람이 자기 이름으로 알아보지
 * 못한다 — 실명을 썼다가 정확히 그 문제를 만들었다(이용자는 자기가 알려준 적 없는
 * 이름을 관리자에게서 듣게 된다).
 *
 * 그래서 표현을 옮겨 적지 않고 **함수 하나로 묶는다.** 두 화면이 각자 `penName ?? email`을
 * 적어 두면 언젠가 한쪽만 고쳐지고, 그때 둘이 갈라진 사실은 아무도 모른다.
 *
 * ⚠ 필명이 없으면 `email`이 나오는데, 이 서비스는 이메일을 받지 않아서 그 칸은
 * 본인 인증 CI 해시로 채운 자리표시자다(`authService`). 즉 **필명 없는 이용자는
 * 아직 앱 어디에도 부를 이름이 없다** — 그 사실을 관리 화면에서 지어내지 않는다.
 * 고칠 자리는 여기가 아니라 "필명 없는 사람을 앱이 뭐라고 부를 것인가"이고,
 * 그것이 정해지면 이 함수 한 곳만 바꾸면 두 화면이 함께 따라온다.
 */
export function displayName(user: { penName?: string | null; email: string }): string {
  return user.penName?.trim() || user.email;
}
